create table if not exists public.linh_responses (
  id bigint generated by default as identity primary key,
  answers jsonb not null,
  submitted_at timestamptz not null default now()
);

alter table public.linh_responses enable row level security;

drop policy if exists "Anyone can submit answers" on public.linh_responses;
create policy "Anyone can submit answers"
on public.linh_responses
for insert to anon, authenticated
with check (true);

drop policy if exists "Admins can read answers" on public.linh_responses;
create policy "Admins can read answers"
on public.linh_responses
for select to authenticated
using (true);

-- SQL privileges are separate from RLS policies.
grant usage on schema public to anon, authenticated;
grant insert on table public.linh_responses to anon, authenticated;
grant select on table public.linh_responses to authenticated;
grant usage, select on sequence public.linh_responses_id_seq to anon, authenticated;