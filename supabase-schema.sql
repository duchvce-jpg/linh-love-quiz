-- Chạy trong Supabase SQL Editor.
create table if not exists public.linh_responses (
  id bigint generated by default as identity primary key,
  answers jsonb not null,
  submitted_at timestamptz not null default now()
);
alter table public.linh_responses enable row level security;
-- Khách được gửi câu trả lời, nhưng không được đọc dữ liệu.
drop policy if exists "Anyone can submit answers" on public.linh_responses;
create policy "Anyone can submit answers" on public.linh_responses for insert to anon, authenticated with check (true);
-- Chỉ tài khoản đã đăng nhập mới được xem câu trả lời.
drop policy if exists "Admins can read answers" on public.linh_responses;
create policy "Admins can read answers" on public.linh_responses for select to authenticated using (true);
